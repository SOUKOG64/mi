"""Domain: интерфейсы репозиториев (реализуются в Infrastructure)."""
from abc import ABC, abstractmethod


class UserRepository(ABC):
    @abstractmethod
    def locations(self, server): ...
    @abstractmethod
    def register(self, server, name, password, location): ...
    @abstractmethod
    def login(self, server, name, password): ...
    @abstractmethod
    def restore(self): ...
    @abstractmethod
    def saved_server(self): ...
    @abstractmethod
    def logout(self): ...
    @abstractmethod
    def update_profile(self, name, location, notify): ...


class AdRepository(ABC):
    @abstractmethod
    def feed(self, flt): ...
    @abstractmethod
    def get(self, ad_id): ...
    @abstractmethod
    def create(self, ad_type, title, description, category): ...
    @abstractmethod
    def set_status(self, ad_id, status): ...
    @abstractmethod
    def mine(self, status): ...
    @abstractmethod
    def report(self, ad_id, reason): ...
    @abstractmethod
    def respond(self, ad_id): ...


class ChatRepository(ABC):
    @abstractmethod
    def chats(self): ...
    @abstractmethod
    def messages(self, chat_id, after): ...
    @abstractmethod
    def send(self, chat_id, text): ...


class ModerationRepository(ABC):
    @abstractmethod
    def reports(self): ...
    @abstractmethod
    def resolve(self, report_id, action): ...
    @abstractmethod
    def block(self, user_id, blocked): ...


class NotificationRepository(ABC):
    @abstractmethod
    def poll(self): ...
